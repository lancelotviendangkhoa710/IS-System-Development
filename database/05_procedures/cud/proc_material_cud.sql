-- Procedure thêm nguyên liệu
CREATE OR REPLACE PROCEDURE PROC_THEM_NGUYENLIEU (
    P_TENNL IN NGUYENLIEU.TENNL%type,
    P_XUATXU IN NGUYENLIEU.XUATXU%type,
    P_MUCTONANTOAN IN NGUYENLIEU.MUCTONANTOAN%type,
    P_MADVT IN DONVITINH.MADVT%type,
    P_MANL_OUT OUT NGUYENLIEU.MANL%type
)
IS
BEGIN
    INSERT INTO NGUYENLIEU (TENNL, XUATXU, MUCTONANTOAN, MADVT, THOIDIEMXOA, MANX)
    VALUES (P_TENNL, P_XUATXU, P_MUCTONANTOAN, P_MADVT, NULL, NULL)
    RETURNING MANL INTO P_MANL_OUT;
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_NL_THEM_MOI, 'Lỗi hệ thống khi tạo mới Nguyên Liệu: ' || SQLERRM);
END;
/

-- Procedure sửa nguyên liệu
CREATE OR REPLACE PROCEDURE PROC_SUA_NGUYENLIEU (
    P_MANL IN NGUYENLIEU.MANL%type,
    P_TENNL IN NGUYENLIEU.TENNL%type,
    P_XUATXU IN NGUYENLIEU.XUATXU%type,
    P_MADVT IN NGUYENLIEU.MADVT%type,
    P_MUCTONANTOAN IN NGUYENLIEU.MUCTONANTOAN%type
)
IS
BEGIN
    UPDATE NGUYENLIEU
    SET TENNL = NVL(P_TENNL, TENNL),
        XUATXU = NVL(P_XUATXU, XUATXU),
        MADVT = NVL(P_MADVT, MADVT),
        MUCTONANTOAN = NVL(P_MUCTONANTOAN, MUCTONANTOAN),
        PHIENBAN = PHIENBAN + 1
    WHERE MANL = P_MANL;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_NL_KHONG_TON_TAI, 'Lỗi: Không tìm thấy Nguyên liệu để cập nhật.');
    END IF;
    
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        IF SQLCODE = PKG_ERROR_CODES.ERR_NL_KHONG_TON_TAI THEN RAISE; END IF;
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_NL_CAPNHAT_HE_THONG, 'Lỗi hệ thống khi cập nhật Nguyên Liệu: ' || SQLERRM);
END;
/

-- Procedure Xóa nguyên liệu
CREATE OR REPLACE PROCEDURE PROC_XOA_NGUYENLIEU(
    P_MANL IN NGUYENLIEU.MANL%type,
    P_MANX IN NHANVIEN.MANV%type
)
IS
    V_LST_COUNT NUMBER := 0;
BEGIN
    -- Kiểm tra xem nguyên liệu này đã từng được giao dịch (Nhập/Xuất chưa)
    SELECT COUNT(*) INTO V_LST_COUNT
    FROM CTPHIEUNHAP
    WHERE MANL = P_MANL;

    IF V_LST_COUNT > 0 THEN
        -- Đã có lịch sử -> Tiến hành XÓA MỀM (Soft Delete)
        UPDATE NGUYENLIEU
        SET THOIDIEMXOA = SYSDATE,
            MANX = P_MANX,
            PHIENBAN = PHIENBAN + 1
        WHERE MANL = P_MANL;
    ELSE
        -- Chưa từng cấu thành lịch sử -> Cho phép XÓA CỨNG (Hard Delete) triệt để
        DELETE FROM NGUYENLIEU WHERE MANL = P_MANL;
    END IF;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_NL_KHONG_TON_TAI, 'Lỗi: Không tìm thấy Nguyên liệu để xóa.');
    END IF;
    
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        IF SQLCODE = PKG_ERROR_CODES.ERR_NL_KHONG_TON_TAI THEN RAISE; END IF;
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_NL_XOA_HE_THONG, 'Lỗi hệ thống khi xóa Nguyên Liệu: ' || SQLERRM);
END;
/

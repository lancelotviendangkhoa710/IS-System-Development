    WHEN OTHERS THEN
        ROLLBACK;
        IF SQLCODE = -20802 THEN RAISE; END IF;
        RAISE_APPLICATION_ERROR(-20803, 'Lỗi hệ thống khi xóa công thức: ' || SQLERRM);
END;

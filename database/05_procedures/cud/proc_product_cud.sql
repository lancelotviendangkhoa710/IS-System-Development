-- Procedure Xóa sản phẩm
CREATE OR REPLACE PROCEDURE PROC_XOA_SANPHAM(
    P_MASP IN NUMBER,
    P_MANX IN NUMBER
)
IS
    V_ORDER_COUNT NUMBER := 0;
BEGIN
    -- Kiểm tra nếu Bánh đã từng được đặt thì mới XÓA MỀM
    SELECT COUNT(*) INTO V_ORDER_COUNT FROM CTDONHANG WHERE MASP = P_MASP;

    IF V_ORDER_COUNT > 0 THEN
        UPDATE SANPHAM 
        SET THOIDIEMXOA = SYSDATE, 
            MANX = P_MANX,
            PHIENBAN = PHIENBAN + 1
        WHERE MASP = P_MASP;
    ELSE
        -- Nếu chưa từng phát sinh doanh số, cho phép XỎA CỨNG
        DELETE FROM SANPHAM WHERE MASP = P_MASP;
    END IF;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20649, 'Lỗi: Không tìm thấy Sản phẩm để xóa.');
    END IF;
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        IF SQLCODE = -20649 THEN RAISE; END IF;
        RAISE_APPLICATION_ERROR(-20650, 'Lỗi hệ thống khi xóa Sản phẩm: ' || SQLERRM);
END;
/


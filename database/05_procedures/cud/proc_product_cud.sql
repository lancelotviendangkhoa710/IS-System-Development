-- Procedure Xóa sản phẩm
CREATE OR REPLACE PROCEDURE PROC_XOA_SANPHAM (
    P_MASP IN SANPHAM.MASP%type,
    P_MANX IN NHANVIEN.MANV%type
)
IS
    V_ORDER_COUNT NUMBER := 0;
BEGIN
    -- Kiểm tra nếu Bánh đã từng được đặt thì mới XÓA MỀM
    SELECT COUNT(*) INTO V_ORDER_COUNT FROM CTDONHANG WHERE MASP = P_MASP;

    IF V_ORDER_COUNT > 0 THEN
        UPDATE SANPHAM 
        SET THOIDIEMXOA = SYSDATE, 
            MANX = P_MANX,
            PHIENBAN = PHIENBAN + 1
        WHERE MASP = P_MASP;
    ELSE
        -- Nếu chưa từng phát sinh doanh số, cho phép XÓA CỨNG
        DELETE FROM SANPHAM WHERE MASP = P_MASP;
    END IF;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_SANPHAM_KHONG_TON_TAI_XOA, 'Lỗi: Không tìm thấy Sản phẩm để xóa.');
    END IF;
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        IF SQLCODE = PKG_ERROR_CODES.ERR_SANPHAM_KHONG_TON_TAI_XOA THEN RAISE; END IF;
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_SANPHAM_XOA_HE_THONG, 'Lỗi hệ thống khi xóa Sản phẩm: ' || SQLERRM);
END;

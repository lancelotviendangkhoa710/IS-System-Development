-- Procedure Thêm sản phẩm (tự động tính giá vốn/giá bán nếu không truyền vào)
CREATE OR REPLACE PROCEDURE PROC_THEM_SANPHAM (
    P_MADM              IN NUMBER,
    P_TENSP             IN NVARCHAR2,
    P_HINHANH           IN VARCHAR2,
    P_CHOPHEPTUYCHINH   IN NUMBER,
    P_THOIGIANBAOQUAN   IN NUMBER,
    P_THOIGIANCHUANBI   IN NUMBER,
    P_GIAVON            IN NUMBER,
    P_GIABAN            IN NUMBER,
    P_MASP_OUT          OUT NUMBER,
    P_MANV_LAP          IN NUMBER DEFAULT NULL
)
IS
    V_GIAVON NUMBER := NVL(P_GIAVON, 0);
    V_GIABAN NUMBER;
BEGIN
    -- 1. Tạo bản ghi sản phẩm; GIAVON/GIABAN = 0 hợp lệ khi chưa có BOM
    INSERT INTO SANPHAM (MADM, TENSP, HINHANH, CHOPHEPTUYCHINH, THOIGIANBAOQUAN, THOIGIANCHUANBI, GIAVON, GIABAN)
    VALUES (P_MADM, P_TENSP, P_HINHANH, P_CHOPHEPTUYCHINH, P_THOIGIANBAOQUAN, P_THOIGIANCHUANBI, V_GIAVON, 0)
    RETURNING MASP INTO P_MASP_OUT;

    -- 2. Tính giá bán: ưu tiên P_GIABAN, fallback tính từ giá vốn; bỏ qua nếu chưa có
    IF NVL(P_GIABAN, 0) > 0 THEN
        V_GIABAN := ROUND(P_GIABAN, -3);
    ELSIF V_GIAVON > 0 THEN
        V_GIABAN := ROUND(V_GIAVON * 2, -3);
    END IF;

    -- 3. Cập nhật giá bán chỉ khi đã tính được
    IF V_GIABAN IS NOT NULL THEN
        UPDATE SANPHAM SET GIABAN = V_GIABAN WHERE MASP = P_MASP_OUT;
    END IF;

    -- 4. Ghi log hoạt động
    IF P_MANV_LAP IS NOT NULL THEN
        INSERT INTO HOATDONGNHANVIEN (MANV, NHOM, HANHDONG, ENTITY_ID)
        VALUES (P_MANV_LAP, 'SAN_PHAM', 'Them SP: ' || P_TENSP || ' (#' || P_MASP_OUT || ')', P_MASP_OUT);
    END IF;

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_SANPHAM_THEM_HE_THONG, 'Lỗi hệ thống khi thêm sản phẩm: ' || SQLERRM);
END;
/

-- Procedure Sửa sản phẩm (tự động tính lại giá vốn/giá bán từ công thức nếu không truyền)
CREATE OR REPLACE PROCEDURE PROC_SUA_SANPHAM (
    P_MASP              IN SANPHAM.MASP%type,
    P_MADM              IN DANHMUCSP.MADM%type,
    P_TENSP             IN SANPHAM.TENSP%type,
    P_HINHANH           IN SANPHAM.HINHANH%type,
    P_CHOPHEPTUYCHINH   IN SANPHAM.CHOPHEPTUYCHINH%type,
    P_THOIGIANBAOQUAN   IN SANPHAM.THOIGIANBAOQUAN%type,
    P_THOIGIANCHUANBI   IN SANPHAM.THOIGIANCHUANBI%type,
    P_GIAVON            IN SANPHAM.GIAVON%type,
    P_GIABAN            IN SANPHAM.GIABAN%type
)
IS
    V_GIAVON NUMBER;
    V_GIABAN NUMBER;
BEGIN
    -- 1. Xác định giá vốn: nếu truyền vào thì dùng, ngược lại tính từ công thức
    IF NVL(P_GIAVON, 0) > 0 THEN
        V_GIAVON := P_GIAVON;
    ELSE
        V_GIAVON := FUNC_TONGGIAVON(P_MASP);
    END IF;

    -- 2. Xác định giá bán: nếu truyền vào thì làm tròn, ngược lại tính theo công thức
    IF NVL(P_GIABAN, 0) > 0 THEN
        V_GIABAN := ROUND(P_GIABAN, -3);
    ELSE
        V_GIABAN := ROUND(V_GIAVON * 2, -3);
    END IF;

    -- 3. Cập nhật toàn bộ thông tin sản phẩm
    UPDATE SANPHAM
    SET MADM              = NVL(P_MADM, MADM),
        TENSP             = NVL(P_TENSP, TENSP),
        HINHANH           = NVL(P_HINHANH, HINHANH),
        CHOPHEPTUYCHINH   = NVL(P_CHOPHEPTUYCHINH, CHOPHEPTUYCHINH),
        THOIGIANBAOQUAN   = NVL(P_THOIGIANBAOQUAN, THOIGIANBAOQUAN),
        THOIGIANCHUANBI   = NVL(P_THOIGIANCHUANBI, THOIGIANCHUANBI),
        GIAVON            = V_GIAVON,
        GIABAN            = V_GIABAN,
        PHIENBAN          = PHIENBAN + 1
    WHERE MASP = P_MASP;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_SANPHAM_KHONG_TON_TAI_CN, 'Lỗi: Không tìm thấy sản phẩm để cập nhật.');
    END IF;
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        IF SQLCODE = PKG_ERROR_CODES.ERR_SANPHAM_KHONG_TON_TAI_CN THEN RAISE; END IF;
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_SANPHAM_CAPNHAT_HE_THONG, 'Lỗi hệ thống khi cập nhật sản phẩm: ' || SQLERRM);
END;
/

-- Procedure Xóa sản phẩm
CREATE OR REPLACE PROCEDURE PROC_XOA_SANPHAM (
    P_MASP IN SANPHAM.MASP%type,
    P_MANX IN NHANVIEN.MANV%type
)
IS
    V_ORDER_COUNT NUMBER := 0;
BEGIN
    SELECT COUNT(*) INTO V_ORDER_COUNT FROM CTDONHANG WHERE MASP = P_MASP;

    IF V_ORDER_COUNT > 0 THEN
        UPDATE SANPHAM
        SET THOIDIEMXOA = SYSDATE,
            MANX = P_MANX,
            PHIENBAN = PHIENBAN + 1
        WHERE MASP = P_MASP;
    ELSE
        DELETE FROM CONGTHUC WHERE MASP = P_MASP;
        DELETE FROM SANPHAM WHERE MASP = P_MASP;
    END IF;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_SANPHAM_KHONG_TON_TAI_XOA, 'Loi: Khong tim thay San pham de xoa.');
    END IF;

    INSERT INTO HOATDONGNHANVIEN (MANV, NHOM, HANHDONG, ENTITY_ID)
    VALUES (P_MANX, 'SAN_PHAM', 'Xoa SP #' || P_MASP, P_MASP);

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        IF SQLCODE = PKG_ERROR_CODES.ERR_SANPHAM_KHONG_TON_TAI_XOA THEN RAISE; END IF;
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_SANPHAM_XOA_HE_THONG, 'Loi he thong khi xoa San pham: ' || SQLERRM);
END;

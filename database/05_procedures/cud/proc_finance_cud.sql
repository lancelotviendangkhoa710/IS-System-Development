    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_PHIEUTHUCHI_THEM_HE_THONG, 'Loi he thong khi tao Phieu thu chi: ' || SQLERRM);
END;

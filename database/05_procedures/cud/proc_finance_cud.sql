
-- Procedure thêm loại thu chi
CREATE OR REPLACE PROCEDURE PROC_THEM_LOAITHUCHI (
    P_TENLOAITHUCHI IN LOAITHUCHI.TENLOAITHUCHI%type,
    P_PHANLOAI IN LOAITHUCHI.PHANLOAI%type,
    P_MALOAITHUCHI_OUT OUT LOAITHUCHI.MALOAITHUCHI%type
)
IS
BEGIN
    INSERT INTO LOAITHUCHI (TENLOAITHUCHI, PHANLOAI, THOIDIEMXOA, MANX)
    VALUES (P_TENLOAITHUCHI, P_PHANLOAI, NULL, NULL)
    RETURNING MALOAITHUCHI INTO P_MALOAITHUCHI_OUT;
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_LOAITHUCHI_THEM_HE_THONG, 'Loi he thong khi them Loai thu chi: ' || SQLERRM);
END;
/

-- Procedure sửa loại thu chi (View Serializable — chống lost update)
CREATE OR REPLACE PROCEDURE PROC_SUA_LOAITHUCHI (
    P_MALOAITHUCHI IN LOAITHUCHI.MALOAITHUCHI%type,
    P_TENLOAITHUCHI IN LOAITHUCHI.TENLOAITHUCHI%type,
    P_PHANLOAI IN LOAITHUCHI.PHANLOAI%type
)
IS
    V_DUMMY NUMBER;
BEGIN
    -- Đặt isolation level SERIALIZABLE cho transaction này
    SET TRANSACTION ISOLATION LEVEL SERIALIZABLE;

    -- Lock row trước khi cập nhật — chống lost update
    SELECT MALOAITHUCHI INTO V_DUMMY
    FROM LOAITHUCHI
    WHERE MALOAITHUCHI = P_MALOAITHUCHI
    FOR UPDATE;

    UPDATE LOAITHUCHI
    SET TENLOAITHUCHI = NVL(P_TENLOAITHUCHI, TENLOAITHUCHI),
        PHANLOAI = NVL(P_PHANLOAI, PHANLOAI)
    WHERE MALOAITHUCHI = P_MALOAITHUCHI;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_LOAITHUCHI_KHONG_TON_TAI_CN, 'Loi: Khong tim thay Loai thu chi de cap nhat.');
    END IF;

    COMMIT;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_LOAITHUCHI_KHONG_TON_TAI_CN, 'Loi: Khong tim thay Loai thu chi de cap nhat.');
    WHEN OTHERS THEN
        ROLLBACK;
        IF SQLCODE = -8177 THEN
            -- ORA-08177: Serializable conflict — row đã bị sửa bởi transaction khác
            RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_LOAITHUCHI_CAPNHAT_HE_THONG, 'Loi: Du lieu da bi thay doi boi nguoi dung khac. Vui long tai lai va thu lai.');
        END IF;
        IF SQLCODE = PKG_ERROR_CODES.ERR_LOAITHUCHI_KHONG_TON_TAI_CN THEN RAISE; END IF;
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_LOAITHUCHI_CAPNHAT_HE_THONG, 'Loi he thong khi cap nhat Loai thu chi: ' || SQLERRM);
END;
/

-- Procedure xóa loại thu chi (View Serializable — chống lost update)
CREATE OR REPLACE PROCEDURE PROC_XOA_LOAITHUCHI(
    P_MALOAITHUCHI IN LOAITHUCHI.MALOAITHUCHI%type,
    P_MANX IN NHANVIEN.MANV%type
)
IS
    V_DUMMY NUMBER;
BEGIN
    -- Đặt isolation level SERIALIZABLE cho transaction này
    SET TRANSACTION ISOLATION LEVEL SERIALIZABLE;

    -- Lock row + kiểm tra chưa bị xóa trước đó
    SELECT MALOAITHUCHI INTO V_DUMMY
    FROM LOAITHUCHI
    WHERE MALOAITHUCHI = P_MALOAITHUCHI
      AND THOIDIEMXOA IS NULL
    FOR UPDATE;

    UPDATE LOAITHUCHI
    SET THOIDIEMXOA = SYSDATE,
        MANX = P_MANX
    WHERE MALOAITHUCHI = P_MALOAITHUCHI;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_LOAITHUCHI_KHONG_TON_TAI_XOA, 'Loi: Khong tim thay Loai thu chi de xoa.');
    END IF;

    COMMIT;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_LOAITHUCHI_KHONG_TON_TAI_XOA, 'Loi: Loai thu chi khong ton tai hoac da bi xoa truoc do.');
    WHEN OTHERS THEN
        ROLLBACK;
        IF SQLCODE = -8177 THEN
            RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_LOAITHUCHI_XOA_HE_THONG, 'Loi: Du lieu da bi thay doi boi nguoi dung khac. Vui long tai lai va thu lai.');
        END IF;
        IF SQLCODE = PKG_ERROR_CODES.ERR_LOAITHUCHI_KHONG_TON_TAI_XOA THEN RAISE; END IF;
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_LOAITHUCHI_XOA_HE_THONG, 'Loi he thong khi xoa Loai thu chi: ' || SQLERRM);
END;
/


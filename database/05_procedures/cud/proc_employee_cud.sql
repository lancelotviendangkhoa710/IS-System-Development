-- Procedure thêm nhân viên (Đã cập nhật cho N-N)
CREATE OR REPLACE PROCEDURE PROC_THEM_NHANVIEN (
    P_HOTEN IN NHANVIEN.HOTEN%type,
    P_NGAYSINH IN NHANVIEN.NGAYSINH%type,
    P_SDT IN NHANVIEN.SDT%type,
    P_TENDANGNHAP IN NHANVIEN.TENDANGNHAP%type,
    P_MATKHAU IN NHANVIEN.MATKHAU%type,
    P_TRANGTHAILAMVIEC IN NHANVIEN.TRANGTHAILAMVIEC%type,
    P_MANV_OUT OUT NHANVIEN.MANV%type
)
IS
    V_COUNT NUMBER;
BEGIN
    -- 1. Kiểm tra trùng SĐT
    SELECT COUNT(*) INTO V_COUNT FROM NHANVIEN WHERE SDT = P_SDT;
    IF V_COUNT > 0 THEN
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_NV_SDT_TON_TAI, 'Lỗi: Số điện thoại này đã được sử dụng bởi nhân viên khác.');
    END IF;

    -- 2. Kiểm tra trùng Tên đăng nhập
    SELECT COUNT(*) INTO V_COUNT FROM NHANVIEN WHERE UPPER(TENDANGNHAP) = UPPER(P_TENDANGNHAP);
    IF V_COUNT > 0 THEN
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_NV_TENDANGNHAP_TON_TAI, 'Lỗi: Tên đăng nhập này đã tồn tại trong hệ thống.');
    END IF;

    INSERT INTO NHANVIEN (HOTEN, NGAYSINH, SDT, TENDANGNHAP, MATKHAU, TRANGTHAILAMVIEC)
    VALUES (P_HOTEN, P_NGAYSINH, P_SDT, P_TENDANGNHAP, P_MATKHAU, NVL(P_TRANGTHAILAMVIEC, 1))
    RETURNING MANV INTO P_MANV_OUT;
    
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
/

-- Procedure gán vai trò cho nhân viên
CREATE OR REPLACE PROCEDURE PROC_GAN_VAITRO_NHANVIEN (
    P_MANV IN NUMBER,
    P_MAVAITRO IN NUMBER
)
IS
BEGIN
    INSERT INTO NHANVIEN_VAITRO (MANV, MAVAITRO)
    SELECT P_MANV, P_MAVAITRO FROM DUAL
    WHERE NOT EXISTS (SELECT 1 FROM NHANVIEN_VAITRO WHERE MANV = P_MANV AND MAVAITRO = P_MAVAITRO);
    COMMIT;
END;
/

-- Procedure cập nhật ma trận quyền chi tiết cho vai trò
CREATE OR REPLACE PROCEDURE PROC_CAPNHAT_QUYEN_CHI_TIET (
    P_MAVAITRO IN NUMBER,
    P_MACHUCNANG IN NUMBER,
    P_VIEW IN NUMBER,
    P_ADD IN NUMBER,
    P_EDIT IN NUMBER,
    P_DELETE IN NUMBER,
    P_DOWNLOAD IN NUMBER
)
IS
BEGIN
    MERGE INTO VAITRO_CHUCNANG vc
    USING (SELECT P_MAVAITRO as VT, P_MACHUCNANG as CN FROM DUAL) src
    ON (vc.MAVAITRO = src.VT AND vc.MACHUCNANG = src.CN)
    WHEN MATCHED THEN
        UPDATE SET CAN_VIEW = P_VIEW, CAN_ADD = P_ADD, CAN_EDIT = P_EDIT, 
                   CAN_DELETE = P_DELETE, CAN_DOWNLOAD = P_DOWNLOAD
    WHEN NOT MATCHED THEN
        INSERT (MAVAITRO, MACHUCNANG, CAN_VIEW, CAN_ADD, CAN_EDIT, CAN_DELETE, CAN_DOWNLOAD)
        VALUES (P_MAVAITRO, P_MACHUCNANG, P_VIEW, P_ADD, P_EDIT, P_DELETE, P_DOWNLOAD);
    COMMIT;
END;
/

-- Procedure sửa nhân viên (Đã cập nhật cho N-N)

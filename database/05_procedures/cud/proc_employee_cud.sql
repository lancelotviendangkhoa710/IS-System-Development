    -- 2. Cap nhat tai khoan dang nhap
    UPDATE TAIKHOAN
    SET TENDANGNHAP = NVL(P_TENDANGNHAP, TENDANGNHAP),
        MATKHAU = NVL(P_MATKHAU, MATKHAU)
    WHERE MANV = P_MANV;

    COMMIT;

-- Procedure them nhan vien (Tach NHANVIEN va TAIKHOAN)
CREATE OR REPLACE PROCEDURE PROC_THEM_NHANVIEN (
    P_HOTEN IN NHANVIEN.HOTEN%type,
    P_NGAYSINH IN NHANVIEN.NGAYSINH%type,
    P_SDT IN NHANVIEN.SDT%type,
    P_DIACHI IN NHANVIEN.DIACHI%type,
    P_TENDANGNHAP IN TAIKHOAN.TENDANGNHAP%type,
    P_MATKHAU IN TAIKHOAN.MATKHAU%type,
    P_TRANGTHAILAMVIEC IN NHANVIEN.TRANGTHAILAMVIEC%type,
    P_MANV_OUT OUT NHANVIEN.MANV%type
)
IS
    V_COUNT NUMBER;
BEGIN
    -- 1. Kiem tra trung SDT
    SELECT COUNT(*) INTO V_COUNT FROM NHANVIEN WHERE SDT = P_SDT;
    IF V_COUNT > 0 THEN
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_NV_SDT_TON_TAI, 'Loi: So dien thoai nay da duoc su dung boi nhan vien khac.');
    END IF;

    -- 2. Kiem tra trung ten dang nhap
    SELECT COUNT(*) INTO V_COUNT FROM TAIKHOAN WHERE UPPER(TENDANGNHAP) = UPPER(P_TENDANGNHAP);
    IF V_COUNT > 0 THEN
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_NV_TENDANGNHAP_TON_TAI, 'Loi: Ten dang nhap nay da ton tai trong he thong.');
    END IF;

    -- 3. Them ho so nhan su
    INSERT INTO NHANVIEN (HOTEN, NGAYSINH, SDT, DIACHI, TRANGTHAILAMVIEC)
    VALUES (P_HOTEN, P_NGAYSINH, P_SDT, P_DIACHI, NVL(P_TRANGTHAILAMVIEC, 1))
    RETURNING MANV INTO P_MANV_OUT;

    -- 4. Tao tai khoan dang nhap
    INSERT INTO TAIKHOAN (MANV, TENDANGNHAP, MATKHAU, TRANGTHAITK)
    VALUES (P_MANV_OUT, P_TENDANGNHAP, P_MATKHAU, 1);

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
/

-- Procedure gan vai tro cho nhan vien
CREATE OR REPLACE PROCEDURE PROC_GAN_VAITRO_NHANVIEN (
    P_MANV IN NUMBER,
    P_MAVAITRO IN NUMBER
)
IS
BEGIN
    INSERT INTO NHANVIEN_VAITRO (MANV, MAVAITRO)
    SELECT P_MANV, P_MAVAITRO FROM DUAL
    WHERE NOT EXISTS (SELECT 1 FROM NHANVIEN_VAITRO WHERE MANV = P_MANV AND MAVAITRO = P_MAVAITRO);
    COMMIT;
END;
/

-- Procedure cap nhat ma tran quyen chi tiet cho vai tro
CREATE OR REPLACE PROCEDURE PROC_CAPNHAT_QUYEN_CHI_TIET (
    P_MAVAITRO IN NUMBER,
    P_MACHUCNANG IN NUMBER,
    P_VIEW IN NUMBER,
    P_ADD IN NUMBER,
    P_EDIT IN NUMBER,
    P_DELETE IN NUMBER,
    P_DOWNLOAD IN NUMBER
)
IS
BEGIN
    MERGE INTO VAITRO_CHUCNANG vc
    USING (SELECT P_MAVAITRO as VT, P_MACHUCNANG as CN FROM DUAL) src
    ON (vc.MAVAITRO = src.VT AND vc.MACHUCNANG = src.CN)
    WHEN MATCHED THEN
        UPDATE SET CAN_VIEW = P_VIEW, CAN_ADD = P_ADD, CAN_EDIT = P_EDIT, 
                   CAN_DELETE = P_DELETE, CAN_DOWNLOAD = P_DOWNLOAD
    WHEN NOT MATCHED THEN
        INSERT (MAVAITRO, MACHUCNANG, CAN_VIEW, CAN_ADD, CAN_EDIT, CAN_DELETE, CAN_DOWNLOAD)
        VALUES (P_MAVAITRO, P_MACHUCNANG, P_VIEW, P_ADD, P_EDIT, P_DELETE, P_DOWNLOAD);
    COMMIT;
END;
/

-- Procedure sua nhan vien (Tach NHANVIEN va TAIKHOAN)
CREATE OR REPLACE PROCEDURE PROC_SUA_NHANVIEN (
    P_MANV IN NHANVIEN.MANV%type,
    P_HOTEN IN NHANVIEN.HOTEN%type,
    P_NGAYSINH IN NHANVIEN.NGAYSINH%type,
    P_SDT IN NHANVIEN.SDT%type,
    P_DIACHI IN NHANVIEN.DIACHI%type,
    P_TENDANGNHAP IN TAIKHOAN.TENDANGNHAP%type,
    P_MATKHAU IN TAIKHOAN.MATKHAU%type,
    P_TRANGTHAILAMVIEC IN NHANVIEN.TRANGTHAILAMVIEC%type
)
IS
BEGIN
    -- 1. Cap nhat ho so nhan su
    UPDATE NHANVIEN
    SET HOTEN = NVL(P_HOTEN, HOTEN),

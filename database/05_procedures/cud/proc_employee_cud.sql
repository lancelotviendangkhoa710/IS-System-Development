-- Procedure cho nhan vien thoi viec (Soft terminate — khong xoa du lieu)
CREATE OR REPLACE PROCEDURE PROC_THOIVIEC_NHANVIEN (
    P_MANV IN NHANVIEN.MANV%type
)
IS
BEGIN
    UPDATE NHANVIEN SET TRANGTHAILAMVIEC = 0 WHERE MANV = P_MANV;
    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_NV_KHONG_TON_TAI_CN, 'Loi: Khong tim thay Nhan vien de cap nhat.');
    END IF;
   
    UPDATE TAIKHOAN SET TRANGTHAITK = 0 WHERE MANV = P_MANV;
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        IF SQLCODE = PKG_ERROR_CODES.ERR_NV_KHONG_TON_TAI_CN THEN RAISE; END IF;
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_NV_XOA_HE_THONG, 'Loi he thong khi cho thoi viec: ' || SQLERRM);
END;
/

-- Procedure them vai tro
CREATE OR REPLACE PROCEDURE PROC_THEM_VAITRO (
    P_TENVAITRO IN VAITRO.TENVAITRO%type,
    P_MOTA IN VAITRO.MOTA%type DEFAULT NULL,
    P_MAVAITRO_OUT OUT VAITRO.MAVAITRO%type
)

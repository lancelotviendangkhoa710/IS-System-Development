-- Procedure thêm vai trò
CREATE OR REPLACE PROCEDURE PROC_THEM_VAITRO (
    P_TENVAITRO IN VAITRO.TENVAITRO%type,
    P_MOTA IN VAITRO.MOTA%type DEFAULT NULL,
    P_MAVAITRO_OUT OUT VAITRO.MAVAITRO%type
)
IS
BEGIN
    INSERT INTO VAITRO (TENVAITRO, MOTA, THOIDIEMXOA, MANX)
    VALUES (P_TENVAITRO, P_MOTA, NULL, NULL)
    RETURNING MAVAITRO INTO P_MAVAITRO_OUT;
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_VAITRO_THEM_HE_THONG, 'Lỗi hệ thống khi thêm Vai trò: ' || SQLERRM);
END;
/

-- Procedure sửa vai trò
CREATE OR REPLACE PROCEDURE PROC_SUA_VAITRO (
    P_MAVAITRO IN VAITRO.MAVAITRO%type,
    P_TENVAITRO IN VAITRO.TENVAITRO%type,
    P_MOTA IN VAITRO.MOTA%type
)
IS
BEGIN
    UPDATE VAITRO
    SET TENVAITRO = NVL(P_TENVAITRO, TENVAITRO),
        MOTA = NVL(P_MOTA, MOTA)
    WHERE MAVAITRO = P_MAVAITRO;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_VAITRO_KHONG_TON_TAI_CN, 'Lỗi: Không tìm thấy Vai trò để cập nhật.');
    END IF;

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        IF SQLCODE = PKG_ERROR_CODES.ERR_VAITRO_KHONG_TON_TAI_CN THEN RAISE; END IF;
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_VAITRO_CAPNHAT_HE_THONG, 'Lỗi hệ thống khi cập nhật Vai trò: ' || SQLERRM);
END;
/


-- --------------------------------------------------------------
-- 1. CUD HẠNG THÀNH VIÊN
-- --------------------------------------------------------------

-- 1.1 Thêm Hạng Thành Viên
CREATE OR REPLACE PROCEDURE PROC_THEM_HANGTHANHVIEN(
    P_TENHANG IN NVARCHAR2,
    P_DIEMTOITHIEU IN NUMBER,
    P_PHANTRAMGIAMGIA IN NUMBER,
    P_MANV_TAO IN NUMBER,
    P_MAHANG_OUT OUT NUMBER
)
IS
BEGIN
    INSERT INTO HANGTHANHVIEN (TENHANG, DIEMTOITHIEU, PHANTRAMGIAMGIA, THOIDIEMXOA, MANX)
    VALUES (P_TENHANG, NVL(P_DIEMTOITHIEU, 0), NVL(P_PHANTRAMGIAMGIA, 0), NULL, NULL)
    RETURNING MAHANG INTO P_MAHANG_OUT;
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_HANGTV_THEM_HE_THONG, 'Lỗi hệ thống khi thêm Hạng Thành Viên (Transaction Rollbacked): ' || SQLERRM);
END;
/

-- 1.2 Cập nhật Hạng Thành Viên
CREATE OR REPLACE PROCEDURE PROC_CAPNHAT_HANGTHANHVIEN(
    P_MAHANG IN NUMBER,
    P_TENHANG IN NVARCHAR2,
    P_DIEMTOITHIEU IN NUMBER,
    P_PHANTRAMGIAMGIA IN NUMBER
)
IS
BEGIN
    UPDATE HANGTHANHVIEN
    SET TENHANG = NVL(P_TENHANG, TENHANG),
        DIEMTOITHIEU = NVL(P_DIEMTOITHIEU, DIEMTOITHIEU),
        PHANTRAMGIAMGIA = NVL(P_PHANTRAMGIAMGIA, PHANTRAMGIAMGIA)
    WHERE MAHANG = P_MAHANG;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_HANGTV_KHONG_TON_TAI_CN, 'Lỗi: Không tìm thấy Hạng Thành Viên để cập nhật.');
    END IF;
    
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        IF SQLCODE = PKG_ERROR_CODES.ERR_HANGTV_KHONG_TON_TAI_CN THEN RAISE; END IF;
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_HANGTV_CAPNHAT_HE_THONG, 'Lỗi hệ thống khi cập nhật Hạng Thành Viên (Transaction Rollbacked): ' || SQLERRM);
END;
/

-- 1.3 Xóa Hạng Thành Viên (XÓA MỀM)
CREATE OR REPLACE PROCEDURE PROC_XOA_HANGTHANHVIEN(
    P_MAHANG IN NUMBER,
    P_MANV_XOA IN NUMBER
)
IS
BEGIN
    UPDATE HANGTHANHVIEN
    SET THOIDIEMXOA = SYSDATE,
        MANX = P_MANV_XOA
    WHERE MAHANG = P_MAHANG;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_HANGTV_KHONG_TON_TAI_XOA, 'Lỗi: Không tìm thấy Hạng Thành Viên để xóa.');
    END IF;
    
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        IF SQLCODE = PKG_ERROR_CODES.ERR_HANGTV_KHONG_TON_TAI_XOA THEN RAISE; END IF;
        RAISE_APPLICATION_ERROR(PKG_ERROR_CODES.ERR_HANGTV_XOA_HE_THONG, 'Lỗi hệ thống khi xóa Hạng Thành Viên (Transaction Rollbacked): ' || SQLERRM);
END;
/

-- --------------------------------------------------------------

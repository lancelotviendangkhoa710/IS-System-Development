-- 2.1 Thêm Khách Hàng
CREATE OR REPLACE PROCEDURE PROC_THEM_KHACHHANG(
    P_HOTEN IN NVARCHAR2,
    P_SDT IN VARCHAR2,
    P_DIACHI IN NVARCHAR2,
    P_DIEMTICHLUY IN NUMBER DEFAULT 0,
    P_MAHANG IN NUMBER DEFAULT NULL,
    P_MANV_TAO IN NUMBER,
    P_MAKH_OUT OUT NUMBER
)
IS
BEGIN

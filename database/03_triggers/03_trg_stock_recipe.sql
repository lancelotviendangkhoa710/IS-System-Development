-- Trigger trừ số lượng tồn tổng của một nguyên liệu khi thực hiện việc xuất nguyên liệu để làm bánh
CREATE OR REPLACE TRIGGER TRG_XUATSLNGUYENLIEU
AFTER INSERT OR UPDATE OR DELETE ON CTPHIEUXUAT_NL
FOR EACH ROW
DECLARE
    V_MALO NUMBER;
    V_MANL NUMBER;
    V_CHENHLECH NUMBER := 0;
BEGIN
    IF INSERTING THEN
        V_CHENHLECH := :NEW.SOLUONG;
        V_MALO := :NEW.MALO;
    ELSIF UPDATING THEN
        V_CHENHLECH := :NEW.SOLUONG - :OLD.SOLUONG;
        V_MALO := :NEW.MALO;
    ELSIF DELETING THEN
        V_CHENHLECH := -(:OLD.SOLUONG);
        V_MALO := :OLD.MALO;
    END IF;

    SELECT MANL INTO V_MANL
    FROM CTPHIEUNHAP
    WHERE MALO = V_MALO;

    UPDATE CTPHIEUNHAP
    SET SOLUONGCONLAI = SOLUONGCONLAI - V_CHENHLECH
    WHERE MALO = V_MALO;

    UPDATE NGUYENLIEU
    SET SOLUONGTONTONG = SOLUONGTONTONG - V_CHENHLECH
    WHERE MANL = V_MANL;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20001, 'Loi: Khong tim thay lo hang trong kho.');
END;
/

-- Trigger cập nhật giá vốn trung bình và số lượng tồn tổng
CREATE OR REPLACE TRIGGER TRG_GIAVONTRUNGBINH_SOLUONGTONTONG
AFTER INSERT ON CTPHIEUNHAP
FOR EACH ROW
DECLARE
    V_TONCU NUMBER(10,2) := 0;
    V_GIACU NUMBER(15,2) := 0;
    V_TONGSOLUONGMOI NUMBER(10,2) := 0;
    V_GIAVONMOI NUMBER(15,2) := 0;
BEGIN
    SELECT NVL(SOLUONGTONTONG, 0), NVL(GIAVONTRUNGBINH, 0)
    INTO V_TONCU, V_GIACU
    FROM NGUYENLIEU
    WHERE MANL = :NEW.MANL;

    V_TONGSOLUONGMOI := V_TONCU + :NEW.SOLUONG;

    IF V_TONGSOLUONGMOI > 0 THEN
        V_GIAVONMOI := ((V_TONCU * V_GIACU) + (:NEW.SOLUONG * :NEW.DONGIA)) / V_TONGSOLUONGMOI;
    ELSE
        V_GIAVONMOI := V_GIACU;
    END IF;

    UPDATE NGUYENLIEU
    SET GIAVONTRUNGBINH = V_GIAVONMOI,
        SOLUONGTONTONG = V_TONGSOLUONGMOI
    WHERE MANL = :NEW.MANL;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20001, 'Loi: Khong tim thay du lieu nguyen lieu.');
END;
/

-- Trigger tính tổng tiền phiếu nhập kho
CREATE OR REPLACE TRIGGER TRG_TONGTIENNHAP
AFTER INSERT OR UPDATE OR DELETE ON CTPHIEUNHAP
FOR EACH ROW
DECLARE
    V_MAPN NUMBER;
    V_CHENHLECH NUMBER(15,2);
BEGIN
    IF INSERTING THEN
        V_CHENHLECH := :NEW.DONGIA * :NEW.SOLUONG;
        V_MAPN := :NEW.MAPN;
    ELSIF UPDATING THEN
        V_CHENHLECH := :NEW.DONGIA * :NEW.SOLUONG - :OLD.DONGIA * :OLD.SOLUONG;
        V_MAPN := :NEW.MAPN;
    ELSIF DELETING THEN
        V_CHENHLECH := -(:OLD.DONGIA * :OLD.SOLUONG);
        V_MAPN := :OLD.MAPN;
    END IF;

    UPDATE PHIEUNHAPKHO
    SET TONGTIENNHAP = NVL(TONGTIENNHAP, 0) + V_CHENHLECH
    WHERE MAPN = V_MAPN;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20001, 'Loi: Khong tim thay du lieu phieu nhap.');
END;
/


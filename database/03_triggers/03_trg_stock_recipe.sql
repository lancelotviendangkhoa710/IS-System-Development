-- Trigger chặn hạn sử dụng chỉ còn 10 ngày kể từ lúc nhập & chống gian lận hạn sử dụng
CREATE OR REPLACE TRIGGER TRG_KIEMTRA_HSD
BEFORE INSERT OR UPDATE OF HANSUDUNG ON CTPHIEUNHAP
FOR EACH ROW
DECLARE
    V_NGAYNHAP DATE;
BEGIN
    -- Chống gian lận hạn sử dụng
    IF UPDATING THEN
        IF :NEW.HANSUDUNG > :OLD.HANSUDUNG THEN
            RAISE_APPLICATION_ERROR(-20002,
                'CANH BAO GIAN LAN: Han su dung moi (' || TO_CHAR(:NEW.HANSUDUNG, 'DD/MM/YYYY') ||
                ') khong duoc phep lon hon han su dung cu (' || TO_CHAR(:OLD.HANSUDUNG, 'DD/MM/YYYY') || ').');
        END IF;
    END IF;

    -- Chặn hạn sử dụng chỉ còn 10 ngày kể từ lúc nhập
    SELECT NGAYNHAP INTO V_NGAYNHAP
    FROM PHIEUNHAPKHO
    WHERE MAPN = :NEW.MAPN;

    IF TRUNC(:NEW.HANSUDUNG) <= TRUNC(V_NGAYNHAP) THEN
        RAISE_APPLICATION_ERROR(-20003,
            'LOI NGHIEP VU: Han su dung cua lo nay (' || TO_CHAR(:NEW.HANSUDUNG, 'DD/MM/YYYY') ||
            ') va ngay nhap kho (' || TO_CHAR(V_NGAYNHAP, 'DD/MM/YYYY') || ') da qua han!.');
    END IF;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20004, 'Loi: Khong tim thay phieu nhap kho.');
END;
/

-- Trigger trừ số lượng bánh khi hủy bánh đã hết hạn, không còn bán
CREATE OR REPLACE TRIGGER TRG_TRUKHO_PHIEUXUATTP
AFTER INSERT OR UPDATE OR DELETE ON CTPHIEUXUAT_TP
FOR EACH ROW
DECLARE
    V_MASP NUMBER;
    V_CHENHLECH NUMBER(10,2) := 0;
    V_SOLUONGTON NUMBER(10,2) := 0;
BEGIN
    IF INSERTING THEN
        V_CHENHLECH := :NEW.SOLUONG;
        V_MASP := :NEW.MASP;
    ELSIF UPDATING THEN
        V_CHENHLECH := :NEW.SOLUONG - :OLD.SOLUONG;
        V_MASP := :NEW.MASP;
    ELSIF DELETING THEN
        V_CHENHLECH := -(:OLD.SOLUONG);
        V_MASP := :OLD.MASP;
    END IF;

    UPDATE SANPHAM
    SET SOLUONGTON = SOLUONGTON - V_CHENHLECH
    WHERE MASP = V_MASP;

    SELECT SOLUONGTON INTO V_SOLUONGTON
    FROM SANPHAM
    WHERE MASP = V_MASP;

    IF V_SOLUONGTON < 0 THEN
        RAISE_APPLICATION_ERROR(-20002, 'So luong banh da het!');
    END IF;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20003, 'Loi: Khong tim thay san pham.');
END;
/

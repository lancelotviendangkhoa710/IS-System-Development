-- Test FUNC_DoanhThuTheoPhuongThucTT --
DECLARE
    V_MAVAITRO NUMBER;
    V_MANV NUMBER;
    V_MACA NUMBER;
    V_MAPTTT_TM NUMBER;
    V_MAPTTT_CK NUMBER;
    
    V_CURSOR SYS_REFCURSOR;
    V_TENPTTT NVARCHAR2(100);
    V_TONGDOANHTHU NUMBER;
    V_COUNT NUMBER := 0;
BEGIN
    -- 1. TẠO DỮ LIỆU GIẢ LẬP
    INSERT INTO VAITRO(TENVAITRO) VALUES ('NV') RETURNING MAVAITRO INTO V_MAVAITRO;
    
    INSERT INTO NHANVIEN(MAVAITRO, HOTEN, SDT, TENDANGNHAP, MATKHAU) 
    VALUES (V_MAVAITRO, 'NV TEST DOANH THU', '0988765432', 'TESTDT', '123') 
    RETURNING MANV INTO V_MANV;

    INSERT INTO CALAMVIEC(MANV, TRANGTHAI) VALUES (V_MANV, 'Đang mở') RETURNING MACA INTO V_MACA;
    
    -- Tạo 2 phương thức thanh toán
    INSERT INTO PHUONGTHUCTT(TENPTTT, MANX) VALUES ('Tiền mặt', V_MANV) RETURNING MAPTTT INTO V_MAPTTT_TM;
    INSERT INTO PHUONGTHUCTT(TENPTTT, MANX) VALUES ('Chuyển khoản', V_MANV) RETURNING MAPTTT INTO V_MAPTTT_CK;
    
    -- Tạo 2 hóa đơn (1 cái TM 100k, 1 cái CK 250k)
    INSERT INTO HOADON(MACA, TONGTIENTHANHTOAN, MAPTTT, NGAYXUATHD) VALUES (V_MACA, 100000, V_MAPTTT_TM, SYSDATE);
    INSERT INTO HOADON(MACA, TONGTIENTHANHTOAN, MAPTTT, NGAYXUATHD) VALUES (V_MACA, 250000, V_MAPTTT_CK, SYSDATE);
    
    -- 2. GỌI HÀM (Lọc doanh thu của ngày hôm nay)
    V_CURSOR := FUNC_DOANHTHUTHEOPTTT(TRUNC(SYSDATE) - 1, TRUNC(SYSDATE) + 1);
    
    -- 3. KIỂM TRA BẢNG ẢO
    LOOP
        FETCH V_CURSOR INTO V_TENPTTT, V_TONGDOANHTHU;
        EXIT WHEN V_CURSOR%NOTFOUND;
        
        -- Nếu dòng trả về khớp với dữ liệu giả lập, đếm số lần khớp
        IF V_TENPTTT = 'Tiền mặt' AND V_TONGDOANHTHU = 100000 THEN
            V_COUNT := V_COUNT + 1;
        ELSIF V_TENPTTT = 'Chuyển khoản' AND V_TONGDOANHTHU = 250000 THEN
            V_COUNT := V_COUNT + 1;
        END IF;
    END LOOP;
    CLOSE V_CURSOR;
    
    -- 4. XÓA DỮ LIỆU RÁC
    ROLLBACK;
    
    -- 5. BÁO CÁO KẾT QUẢ
    IF V_COUNT = 2 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Function FUNC_DoanhThuTheoPhuongThucTT hoạt động!');
    ELSE
        RAISE_APPLICATION_ERROR(-20002, 'Function trả về sai dữ liệu hoặc thiếu dòng.');
    END IF;
END;

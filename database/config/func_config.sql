-- Test FUNC_TOPSANPHAMBANCHAY --
DECLARE
    V_MAVAITRO NUMBER;
    V_MANV NUMBER;
    V_MATT_HT NUMBER;
    V_MATT_HUY NUMBER;
    
    V_MADM NUMBER;
    V_MASP_1 NUMBER;
    V_MASP_2 NUMBER;
    V_MASP_3 NUMBER;
    
    V_MADON_1 NUMBER;
    V_MADON_2 NUMBER;
    
    V_CURSOR SYS_REFCURSOR;
    V_TENSP_RESULT NVARCHAR2(100);
    V_TONG_RESULT NUMBER;
    V_COUNT NUMBER := 0;
BEGIN
    -- 1. TẠO DỮ LIỆU ĐỂ TEST
    INSERT INTO VAITRO(TENVAITRO) VALUES ('NV') RETURNING MAVAITRO INTO V_MAVAITRO;
    INSERT INTO NHANVIEN(MAVAITRO, HOTEN, SDT, TENDANGNHAP, MATKHAU) 
    VALUES (V_MAVAITRO, 'NV TEST TOP', '0999555888', 'TESTTOP', '123') 
    RETURNING MANV INTO V_MANV;

    INSERT INTO TRANGTHAIDON(TENTRANGTHAI) VALUES ('Hoàn thành') RETURNING MATRANGTHAI INTO V_MATT_HT;
    -- Tạo trạng thái Hủy để thử thách thuật toán
    INSERT INTO TRANGTHAIDON(TENTRANGTHAI) VALUES ('Hủy') RETURNING MATRANGTHAI INTO V_MATT_HUY;
    
    INSERT INTO DANHMUCSP(TENDM) VALUES ('BÁNH NGỌT') RETURNING MADM INTO V_MADM;
    
    -- TOP 1: Bánh A (Bán 50 cái, Hợp Lệ)
    INSERT INTO SANPHAM(MADM, TENSP, GIACOBAN, SOLUONGTON) VALUES (V_MADM, 'Bánh A', 100000, 100) RETURNING MASP INTO V_MASP_1;
    -- TOP 2: Bánh B (Bán 30 cái, Hợp Lệ)
    INSERT INTO SANPHAM(MADM, TENSP, GIACOBAN, SOLUONGTON) VALUES (V_MADM, 'Bánh B', 100000, 100) RETURNING MASP INTO V_MASP_2;
    -- Bánh C: Bán siêu khủng 100 cái NHƯNG đã bị HỦY (Bom Hàng) -> Phải lờ đi!
    INSERT INTO SANPHAM(MADM, TENSP, GIACOBAN, SOLUONGTON) VALUES (V_MADM, 'Bánh C', 100000, 100) RETURNING MASP INTO V_MASP_3;

    -- Đơn hàng 1 (Nhà vua mua hàng: Hoàn thành)
    INSERT INTO DONDATHANG(NGAYLAP, NGAYGIONHANBANH, MANV_LAP, MATRANGTHAI) 
    VALUES (SYSDATE, SYSDATE, V_MANV, V_MATT_HT) RETURNING MADON INTO V_MADON_1;
    
    INSERT INTO CTDONHANG(MADON, MASP, SOLUONG, DONGIA) VALUES (V_MADON_1, V_MASP_1, 50, 100000);
    INSERT INTO CTDONHANG(MADON, MASP, SOLUONG, DONGIA) VALUES (V_MADON_1, V_MASP_2, 30, 100000);
    
    -- Đơn hàng 2 (Khách bom hàng: Hủy) -> Bánh C bị bom
    INSERT INTO DONDATHANG(NGAYLAP, NGAYGIONHANBANH, MANV_LAP, MATRANGTHAI) 
    VALUES (SYSDATE, SYSDATE, V_MANV, V_MATT_HUY) RETURNING MADON INTO V_MADON_2;
    
    INSERT INTO CTDONHANG(MADON, MASP, SOLUONG, DONGIA) VALUES (V_MADON_2, V_MASP_3, 100, 100000);

    -- 2. GỌI HÀM KIỂM TRA RANKING (Từ hôm qua đến ngày mai)
    V_CURSOR := FUNC_TOPSANPHAMBANCHAY(TRUNC(SYSDATE) - 1, TRUNC(SYSDATE) + 1);
    
    -- 3. KIỂM TRA KẾT QUẢ (Cần quét trúng chính xác Bánh A - 50 và Bánh B - 30)
    LOOP
        FETCH V_CURSOR INTO V_TENSP_RESULT, V_TONG_RESULT;
        EXIT WHEN V_CURSOR%NOTFOUND;
        
        IF V_TENSP_RESULT = 'Bánh A' AND V_TONG_RESULT = 50 THEN
            V_COUNT := V_COUNT + 1;
        ELSIF V_TENSP_RESULT = 'Bánh B' AND V_TONG_RESULT = 30 THEN
            V_COUNT := V_COUNT + 1;
        -- Nếu phát hiện lọt Bánh C "ảo" vào danh sách, đánh sập test ngay lập tức
        ELSIF V_TENSP_RESULT = 'Bánh C' THEN
            V_COUNT := -999;
        END IF;
    END LOOP;
    CLOSE V_CURSOR;
    
    -- 4. XÓA DỮ LIỆU TẠM THỜI
    ROLLBACK;
    
    -- 5. BÁO CÁO KẾT QUẢ CHO CONSOLE
    IF V_COUNT = 2 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Function FUNC_TOPSANPHAMBANCHAY hoạt động!');
    ELSE
        RAISE_APPLICATION_ERROR(-20002, 'Function hoạt động sai! Lọc sai trạng thái hoặc mang ra thể loại bánh bị bom.');
    END IF;
END;

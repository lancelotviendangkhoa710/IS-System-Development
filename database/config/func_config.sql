-- Test FUNC_CHUYENDOITYLECONGTHUC --
DECLARE
    V_MADM NUMBER;
    V_MASP NUMBER;
    V_MADVT_BOT NUMBER;
    V_MADVT_DUONG NUMBER;
    V_MANL_BOT NUMBER;
    V_MANL_DUONG NUMBER;
    
    V_CURSOR SYS_REFCURSOR;
    V_MANL_RESULT NUMBER;
    V_TENNL_RESULT NVARCHAR2(100);
    V_TONG_RESULT NUMBER;
    V_TENDVT_RESULT NVARCHAR2(50);
    
    V_COUNT NUMBER := 0;
BEGIN
    -- 1. TẠO DỮ LIỆU
    INSERT INTO DANHMUCSP(TENDM) VALUES ('BÁNH NƯỚNG') RETURNING MADM INTO V_MADM;
    INSERT INTO SANPHAM(MADM, TENSP, GIACOBAN, SOLUONGTON) VALUES (V_MADM, 'Bánh Nướng Nguyên Ổ', 100000, 100) RETURNING MASP INTO V_MASP;

    -- Đơn vị tính và nguyên liệu
    INSERT INTO DONVITINH(TENDVT) VALUES ('kg') RETURNING MADVT INTO V_MADVT_BOT;
    INSERT INTO DONVITINH(TENDVT) VALUES ('gram') RETURNING MADVT INTO V_MADVT_DUONG;
    
    INSERT INTO NGUYENLIEU(TENNL, MADVT, GIAVONTRUNGBINH) VALUES ('Bột làm bánh', V_MADVT_BOT, 20000) RETURNING MANL INTO V_MANL_BOT;
    INSERT INTO NGUYENLIEU(TENNL, MADVT, GIAVONTRUNGBINH) VALUES ('Đường trắng', V_MADVT_DUONG, 15000) RETURNING MANL INTO V_MANL_DUONG;
    
    -- Công thức cho 1 cái bánh: 0.5 kg Bột và 200 gram Đường
    INSERT INTO CONGTHUC(MASP, MANL, SOLUONGTIEUHAO) VALUES (V_MASP, V_MANL_BOT, 0.5);
    INSERT INTO CONGTHUC(MASP, MANL, SOLUONGTIEUHAO) VALUES (V_MASP, V_MANL_DUONG, 200);

    -- 2. GỌI HÀM: Bếp trưởng Cần làm ráp vòng 10 cái bánh
    -- Kỳ vọng: Bột = 0.5 * 10 = 5 kg
    --          Đường = 200 * 10 = 2000 gram
    V_CURSOR := FUNC_CHUYENDOITYLECONGTHUC(V_MASP, 10);
    
    -- 3. KIỂM TRA KẾT QUẢ (Quét từng dòng của Bảng Ảo)
    LOOP
        FETCH V_CURSOR INTO V_MANL_RESULT, V_TENNL_RESULT, V_TONG_RESULT, V_TENDVT_RESULT;
        EXIT WHEN V_CURSOR%NOTFOUND;
        
        IF V_MANL_RESULT = V_MANL_BOT AND V_TONG_RESULT = 5 AND V_TENDVT_RESULT = 'kg' THEN
            V_COUNT := V_COUNT + 1;
        ELSIF V_MANL_RESULT = V_MANL_DUONG AND V_TONG_RESULT = 2000 AND V_TENDVT_RESULT = 'gram' THEN
            V_COUNT := V_COUNT + 1;
        END IF;
    END LOOP;
    CLOSE V_CURSOR;
    
    -- 4. XOA DỮ LIỆU TẠM
    ROLLBACK;
    
    -- 5. BÁO CÁO KẾT QUẢ
    IF V_COUNT = 2 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Function FUNC_CHUYENDOITYLECONGTHUC hoạt động!');
    ELSE
        RAISE_APPLICATION_ERROR(-20002, 'Function hoạt động sai tỷ lệ quy đổi hoặc thiếu dữ liệu!');
    END IF;
END;

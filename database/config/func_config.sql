    V_MASP NUMBER;
    V_MADVT_BOT NUMBER;
    V_MADVT_TRUNG NUMBER;
    V_MANL_BOT NUMBER;
    V_MANL_TRUNG NUMBER;
    
    V_SO_LUONG_MAX NUMBER;
BEGIN
    -- 1. TẠO DỮ LIỆU ĐỂ TEST
    INSERT INTO DANHMUCSP(TENDM) VALUES ('BÁNH NƯỚNG') RETURNING MADM INTO V_MADM;
    INSERT INTO SANPHAM(MADM, TENSP, GIACOBAN, SOLUONGTON) VALUES (V_MADM, 'Bánh Thử Thắt Cổ Chai', 100000, 0) RETURNING MASP INTO V_MASP;

    -- Đơn vị tính
    INSERT INTO DONVITINH(TENDVT) VALUES ('gram') RETURNING MADVT INTO V_MADVT_BOT;
    INSERT INTO DONVITINH(TENDVT) VALUES ('qua') RETURNING MADVT INTO V_MADVT_TRUNG;
    
    -- Tồn kho hiện tại: Kho còn dư dả 1000 gram Bột, nhưng Trứng thì chỉ còn vỏn vẹn 10 quả
    INSERT INTO NGUYENLIEU(TENNL, MADVT, GIAVONTRUNGBINH, SOLUONGTONTONG) 
    VALUES ('Bột Bắp', V_MADVT_BOT, 100, 1000) RETURNING MANL INTO V_MANL_BOT;
    
    INSERT INTO NGUYENLIEU(TENNL, MADVT, GIAVONTRUNGBINH, SOLUONGTONTONG) 
    VALUES ('Trứng Gà', V_MADVT_TRUNG, 3000, 10) RETURNING MANL INTO V_MANL_TRUNG;
    
    -- Công thức: Đề bài yêu cầu 1 bánh cần 100 gram bột và 2 quả trứng
    INSERT INTO CONGTHUC(MASP, MANL, SOLUONGTIEUHAO) VALUES (V_MASP, V_MANL_BOT, 100);
    INSERT INTO CONGTHUC(MASP, MANL, SOLUONGTIEUHAO) VALUES (V_MASP, V_MANL_TRUNG, 2);

    -- 2. GỌI HÀM KIỂM TRA MỨC ĐỘ THẮT CỔ CHAI
    -- Bột đủ làm: 1000 / 100 = 10 cái bánh
    -- Trứng đủ làm: 10 / 2 = 5 cái bánh
    -- Suy ra điểm thắt cổ chai bị chặn lại ở Trứng => Chỉ nướng được tối đa 5 cái!
    V_SO_LUONG_MAX := FUNC_SOLUONGKHADUNG(V_MASP);
    
    -- 3. XÓA DỮ LIỆU TẠM THỜI
    ROLLBACK;
    
    -- 4. BÁO CÁO KẾT QUẢ CHO CONSOLE
    IF V_SO_LUONG_MAX = 5 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Function FUNC_SOLUONGKHADUNG hoạt động!');
    ELSE
        RAISE_APPLICATION_ERROR(-20002, 'Function hoạt động gặp lỗi sai thuật toán! Tính capacity bị lệch, kết quả hiện tại là: ' || V_SO_LUONG_MAX);
    END IF;
END;

DECLARE
    V_MANV NUMBER;
    V_MAVAITRO NUMBER;
    V_MANL NUMBER;
    V_MANCC NUMBER;
    V_MADVT NUMBER;
    V_MAPN NUMBER;
    V_MAPX NUMBER;
    V_MALO NUMBER;
    V_MADM NUMBER;
    V_MASP NUMBER;
    V_MADON NUMBER;
    V_MACTHD NUMBER;
    V_MAKH NUMBER;
    V_MATT NUMBER;
    V_SOLUONGTON NUMBER;
BEGIN
    -- 1. TẠO DỮ LIỆU CÓ LIÊN QUAN
    INSERT INTO VAITRO(TENVAITRO) VALUES ('NV') RETURNING MAVAITRO INTO V_MAVAITRO;
    INSERT INTO NHANVIEN(MAVAITRO, HOTEN, SDT, TENDANGNHAP, MATKHAU) VALUES (V_MAVAITRO, 'ABC', '999999999', 'USER', '12345') RETURNING MANV INTO V_MANV;
    INSERT INTO DONVITINH(TENDVT) VALUES ('kg') RETURNING MADVT INTO V_MADVT;
    INSERT INTO DANHMUCSP(TENDM) VALUES ('BANH') RETURNING MADM INTO V_MADM;
    INSERT INTO SANPHAM(MADM, TENSP, GIACOBAN, SOLUONGTON) VALUES (V_MADM, 'DONUT', 10000, 10) RETURNING MASP INTO V_MASP;
    INSERT INTO NGUYENLIEU(TENNL, MADVT, GIAVONTRUNGBINH, SOLUONGTONTONG)
    VALUES (N'Bột mì', V_MADVT, 20000, 20) RETURNING MANL INTO V_MANL;
    INSERT INTO NHACUNGCAP(TENNCC) VALUES ('NCC') RETURNING MANCC INTO V_MANCC;
    INSERT INTO PHIEUNHAPKHO(MANV, MANCC) VALUES (V_MANV, V_MANCC) RETURNING MAPN INTO V_MAPN;
    INSERT INTO PHIEUXUATKHO(MANV) VALUES (V_MANV) RETURNING MAPX INTO V_MAPX;
    INSERT INTO TRANGTHAIDON(TENTRANGTHAI) VALUES ('Mới đặt') RETURNING MATRANGTHAI INTO V_MATT;
    INSERT INTO DONDATHANG(NGAYGIONHANBANH, MANV_LAP, MATRANGTHAI) VALUES (SYSDATE, V_MANV, V_MATT) RETURNING MADON INTO V_MADON;

    -- 2. TẠO DỮ LIỆU KÍCH HOẠT TRIGGER
    INSERT INTO CTDONHANG(MADON, MASP, SOLUONG, DONGIA) VALUES (V_MADON, V_MASP, 5, 5000) RETURNING MACTHD INTO V_MACTHD;

    -- 4. ĐỌC LẠI DỮ LIỆU TỪ BẢNG CHA
    SELECT SOLUONGTON INTO V_SOLUONGTON
    FROM SANPHAM
    WHERE MASP = V_MASP;
    -- 5. XÓA DỮ LIỆU TẠM
    ROLLBACK;

    -- 6. BÁO CÁO KẾT QUA
    IF V_SOLUONGTON = 5 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Trigger hoạt động');
    ELSE
        RAISE_APPLICATION_ERROR(-20002, 'Trigger không hoạt động');
    END IF;
END;

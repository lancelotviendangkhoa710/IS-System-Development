-- Test TRG_CTDONHANG_GIAVON --
DECLARE
    V_MAVAITRO NUMBER;
    V_MANV NUMBER;
    V_MADVT NUMBER;
    V_MADM NUMBER;
    V_MASP NUMBER;
    V_MANL NUMBER;
    V_MADON NUMBER;
    V_MATRANGTHAI NUMBER;
    V_MACTHD NUMBER;
    V_DONGIAVON NUMBER;
BEGIN
    -- 1. TẠO DỮ LIỆU CÓ LIÊN QUAN
    INSERT INTO VAITRO(TENVAITRO) VALUES ('NV') RETURNING MAVAITRO INTO V_MAVAITRO;

    INSERT INTO NHANVIEN(MAVAITRO, HOTEN, SDT, TENDANGNHAP, MATKHAU)
    VALUES (V_MAVAITRO, 'NV TEST GIAVON', '0887654321', 'TESTGIAVON', '123')
    RETURNING MANV INTO V_MANV;

    INSERT INTO DONVITINH(TENDVT) VALUES ('kg') RETURNING MADVT INTO V_MADVT;

    INSERT INTO DANHMUCSP(TENDM) VALUES ('BANH') RETURNING MADM INTO V_MADM;

    INSERT INTO SANPHAM(MADM, TENSP, GIACOBAN, SOLUONGTON)
    VALUES (V_MADM, 'BANH TEST GIA VON', 50000, 10)
    RETURNING MASP INTO V_MASP;

    INSERT INTO NGUYENLIEU(TENNL, MADVT, GIAVONTRUNGBINH)
    VALUES ('Bột test', V_MADVT, 20000)
    RETURNING MANL INTO V_MANL;

    -- Thêm công thức: 1 bánh tốn 0.5 kg Bột (Giá vốn lý thuyết = 0.5 * 20000 = 10000)
    INSERT INTO CONGTHUC(MASP, MANL, SOLUONGTIEUHAO)
    VALUES (V_MASP, V_MANL, 0.5);

    INSERT INTO TRANGTHAIDON(TENTRANGTHAI) VALUES ('Mới đặt') RETURNING MATRANGTHAI INTO V_MATRANGTHAI;

    INSERT INTO DONDATHANG(NGAYGIONHANBANH, MANV_LAP, MATRANGTHAI)
    VALUES (SYSDATE, V_MANV, V_MATRANGTHAI)
    RETURNING MADON INTO V_MADON;

    -- 2. KÍCH HOẠT TRIGGER (Thêm chi tiết đơn hàng)
    INSERT INTO CTDONHANG(MADON, MASP, SOLUONG, DONGIA)
    VALUES (V_MADON, V_MASP, 1, 50000)
    RETURNING MACTHD INTO V_MACTHD;

    -- 3. KIỂM TRA KẾT QUẢ GÁN GIÁ VỐN
    SELECT DONGIAVON INTO V_DONGIAVON
    FROM CTDONHANG
    WHERE MACTHD = V_MACTHD;

    -- 4. DỌN DẸP DỮ LIỆU TẠM
    ROLLBACK;

    -- 5. BÁO CÁO KẾT QUẢ
    IF V_DONGIAVON = 10000 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Trigger TRG_CTDONHANG_GIAVON hoạt động đúng');
    ELSE
        RAISE_APPLICATION_ERROR(-20002, 'Trigger TRG_CTDONHANG_GIAVON không hoạt động hoặc tính sai');
    END IF;
END;

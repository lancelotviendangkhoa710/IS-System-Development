-- Test TRG_KIEMSOAT_CONGSUAT_DONHANG & TRG_KIEMSOAT_CONGSUAT_TUYCHINH --
DECLARE
    V_MAVAITRO NUMBER;
    V_MANV NUMBER;
    V_MADM NUMBER;
    V_MASP NUMBER;
    V_MADON NUMBER;
    V_MATRANGTHAI NUMBER;
    V_MACTHD NUMBER;
BEGIN
    -- 1. TẠO DỮ LIỆU CÓ LIÊN QUAN
    INSERT INTO VAITRO(TENVAITRO) VALUES ('NV') RETURNING MAVAITRO INTO V_MAVAITRO;
    
    INSERT INTO NHANVIEN(MAVAITRO, HOTEN, SDT, TENDANGNHAP, MATKHAU) 
    VALUES (V_MAVAITRO, 'NV TEST CONGSUAT', '0887654322', 'TESTCS', '123') 
    RETURNING MANV INTO V_MANV;
    
    INSERT INTO DANHMUCSP(TENDM) VALUES ('BANH') RETURNING MADM INTO V_MADM;
    INSERT INTO SANPHAM(MADM, TENSP, GIACOBAN, SOLUONGTON) 
    VALUES (V_MADM, 'BANH CONG SUAT', 50000, 100) 
    RETURNING MASP INTO V_MASP;
    
    -- Thêm giới hạn công suất cho ngày hôm nay (giới hạn 5 cái)
    INSERT INTO NANGLUCSANXUAT(NGAYSANXUAT, GIOIHANSOBANH, SOBANHDANHAN) 
    VALUES (TRUNC(SYSDATE), 5, 0);
    
    INSERT INTO TRANGTHAIDON(TENTRANGTHAI) VALUES ('Mới đặt') RETURNING MATRANGTHAI INTO V_MATRANGTHAI;
    
    INSERT INTO DONDATHANG(NGAYGIONHANBANH, MANV_LAP, MATRANGTHAI) 
    VALUES (SYSDATE, V_MANV, V_MATRANGTHAI) 
    RETURNING MADON INTO V_MADON;

    -- 2. KÍCH HOẠT TRIGGER (Thêm 6 cái -> Vượt mốc 5 cái)
    BEGIN
        INSERT INTO CTDONHANG(MADON, MASP, SOLUONG, DONGIA) 
        VALUES (V_MADON, V_MASP, 6, 50000)
        RETURNING MACTHD INTO V_MACTHD;
        
        -- Nếu vượt qua block trên mà không bị lỗi -> Trigger sai (hoặc không hoạt động)
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20002, 'Trigger TRG_KIEMSOAT_CONGSUAT không hoạt động để chặn giao dịch');
    EXCEPTION
        WHEN OTHERS THEN
            -- SQLCODE cua Raise_Application_Error(-20005) la -20005
            IF SQLCODE = -20005 THEN
                ROLLBACK;
                RAISE_APPLICATION_ERROR(-20001, 'Trigger TRG_KIEMSOAT_CONGSUAT hoạt động đúng: ' || SQLERRM);
            ELSE
                ROLLBACK;
                RAISE_APPLICATION_ERROR(-20002, 'Lỗi khác bất ngờ: ' || SQLERRM);
            END IF;
    END;
END;

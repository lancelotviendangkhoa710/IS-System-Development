-- Test Procedure --
DECLARE
    V_MAVAITRO NUMBER;
    V_MANV NUMBER;
    V_THOIDIEMXOA TIMESTAMP;
    V_MANX NUMBER;
BEGIN
    -- BƯỚC 1: TẠO DỮ LIỆU CÓ LIÊN QUAN
    INSERT INTO VAITRO(TENVAITRO) VALUES ('NV') RETURNING MAVAITRO INTO V_MAVAITRO;
    INSERT INTO NHANVIEN(MAVAITRO, HOTEN, SDT, TENDANGNHAP, MATKHAU)
    VALUES (V_MAVAITRO, 'ABC', '999999999', 'USER', '12345') RETURNING MANV INTO V_MANV;

    -- BƯỚC 2: TẠO HIỆN TRƯỜNG GIẢ
    UPDATE VAITRO
    SET THOIDIEMXOA = SYSDATE, MANX = V_MANV
    WHERE MAVAITRO = V_MAVAITRO;

    -- BƯỚC 3: GỌI PROCEDURE ĐỂ KHÔI PHỤC
    PROC_KHOIPHUCDULIEU('VAITRO', 'MAVAITRO', V_MAVAITRO);

    -- BƯỚC 4: KHÁM NGHIỆM LẠI HIỆN TRƯỜNG
    SELECT THOIDIEMXOA, MANX
    INTO V_THOIDIEMXOA, V_MANX
    FROM VAITRO
    WHERE MAVAITRO = V_MAVAITRO;

    -- BƯỚC 5: XÓA DỮ LIỆU TẠM
    DELETE FROM NHANVIEN WHERE MANV = V_MANV;
    DELETE FROM VAITRO WHERE MAVAITRO = V_MAVAITRO;
    COMMIT;

    -- BƯỚC 6: BÁO CÁO KẾT QUẢ
    IF V_THOIDIEMXOA IS NULL AND V_MANX IS NULL THEN
        RAISE_APPLICATION_ERROR(-20001, 'Procedure hoat dong');
    ELSE
        RAISE_APPLICATION_ERROR(-20002, 'Procedure khong hoat dong');
    END IF;
END;
/




-- ==========================================

CREATE TABLE DANHMUCSP (
    MaDM NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TenDM NVARCHAR2(100) NOT NULL,
    ThoiDiemXoa TIMESTAMP,
    MaNX NUMBER,
    CONSTRAINT FK_DMSP_NX FOREIGN KEY (MaNX) REFERENCES NHANVIEN(MaNV)
);

CREATE TABLE SANPHAM (
    MaSP NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    MaDM NUMBER NOT NULL,
    TenSP NVARCHAR2(200) NOT NULL,
    GiaCoBan NUMBER(15,2) NOT NULL,
    HinhAnh VARCHAR2(500),
    ChoPhepTuyChinh NUMBER(1) DEFAULT 0,
    ThoiGianBaoQuan NUMBER(5,0),
    SoLuongTon NUMBER(10,2) DEFAULT 0,
    PhienBan NUMBER(10,0) DEFAULT 1,
    ThoiDiemXoa TIMESTAMP,
    MaNX NUMBER,
    CONSTRAINT FK_SP_DM FOREIGN KEY (MaDM) REFERENCES DANHMUCSP(MaDM),
    CONSTRAINT FK_SP_NX FOREIGN KEY (MaNX) REFERENCES NHANVIEN(MaNV)
);

CREATE TABLE KICHCOBANH (
    MaKC NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TenKC NVARCHAR2(50) NOT NULL,
    PhuPhi NUMBER(15,2) DEFAULT 0,
    ThoiDiemXoa TIMESTAMP,
    MaNX NUMBER,
    CONSTRAINT FK_KCB_NX FOREIGN KEY (MaNX) REFERENCES NHANVIEN(MaNV)
);

CREATE TABLE COTBANH (
    MaCot NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TenCot NVARCHAR2(100) NOT NULL,
    PhuPhi NUMBER(15,2) DEFAULT 0,
    ThoiDiemXoa TIMESTAMP,
    MaNX NUMBER,
    CONSTRAINT FK_CB_NX FOREIGN KEY (MaNX) REFERENCES NHANVIEN(MaNV)
);

CREATE TABLE NHANBANH (
    MaNhan NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TenNhan NVARCHAR2(100) NOT NULL,
    PhuPhi NUMBER(15,2) DEFAULT 0,
    ThoiDiemXoa TIMESTAMP,
    MaNX NUMBER,
    CONSTRAINT FK_NB_NX FOREIGN KEY (MaNX) REFERENCES NHANVIEN(MaNV)
);

CREATE TABLE KIEUTRANGTRI (
    MaTrangTri NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TenTrangTri NVARCHAR2(100) NOT NULL,
    PhuPhi NUMBER(15,2) DEFAULT 0,
    ThoiDiemXoa TIMESTAMP,
    MaNX NUMBER,
    CONSTRAINT FK_KTT_NX FOREIGN KEY (MaNX) REFERENCES NHANVIEN(MaNV)
);